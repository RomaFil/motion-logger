/**
 * @file uart_port.h
 * @brief Відкриття послідовного порту для читання рядків GPS: 8N1, без керування потоком,
 * raw-режим.
 *
 * Повертає звичайний файловий дескриптор, який потім читає core/gps_reader через epoll. Якщо
 * шлях веде не до термінала (канал FIFO, файл у тестах), налаштування порту пропускаються, а
 * дескриптор усе одно повертається: так той самий код працює й на платі, і в тестах.
 */
#ifndef UART_PORT_H
#define UART_PORT_H

/**
 * @brief Відкриває порт на читання без блокування і виставляє швидкість.
 *
 * @param path  шлях до порту, наприклад /dev/ttyAMA2
 * @param baud  швидкість у бодах: 4800, 9600, 19200, 38400, 57600 або 115200
 * @return невід'ємний дескриптор при успіху; -EINVAL, якщо path NULL чи швидкість не з переліку;
 *         інакше мінус errno відкриття або налаштування порту
 */
int uart_port_open(const char *path, unsigned int baud);

#endif /* UART_PORT_H */
