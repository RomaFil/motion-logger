/**
 * @file io_util.h
 * @brief Дрібні спільні функції введення-виведення, потрібні кільком програмам проєкту.
 */
#ifndef IO_UTIL_H
#define IO_UTIL_H

#include <stddef.h>

/**
 * @brief Записує в дескриптор усі length байтів, навіть якщо write() віддає їх частинами.
 *
 * write() має право записати менше, ніж просили (наприклад, при перериванні сигналом
 * або повному каналі), тому одного виклику недостатньо. Функція повторює запис, поки
 * не запише все або не зустріне помилку.
 *
 * @param fd     дескриптор, відкритий на запис
 * @param data   що записати
 * @param length скільки байтів
 * @return 0 при успіху; мінус код помилки системи (наприклад, -EPIPE, -ENOSPC)
 */
int write_all(int fd, const void *data, size_t length);

#endif /* IO_UTIL_H */
