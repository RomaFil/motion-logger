/**
 * @file log_writer.h
 * @brief Окремий потік, що забирає числа з кільцевого буфера й дописує їх у лог-файл.
 *
 * Один рядок файлу це один запис у форматі JSON (так файл легко читає і людина, і програма):
 *   {"t_ms":123456,"src":"sim","value":42}
 *
 * t_ms це мілісекунди монотонного годинника (з моменту старту системи). Звичайний
 * годинник тут не годиться: на Raspberry Pi 5 нема батарейки RTC, і поки мережа не
 * виставила час, він показує невірну дату та може стрибнути назад. Монотонний годинник
 * лише росте, тож порядок записів завжди правильний.
 *
 * Час ставиться в момент ЗАПИСУ в файл, а не вимірювання. Поки число лежало в буфері,
 * минуло кілька мілісекунд. Для 100 відліків на секунду це допустимо; коли в буфер
 * піде структура з власною міткою часу, ця неточність зникне.
 *
 * Кожен запис іде одним викликом write() у файл, відкритий з O_APPEND, тому рядок не
 * буває "наполовину": після зупинки програми файл закінчується повним рядком.
 */
#ifndef LOG_WRITER_H
#define LOG_WRITER_H

#include <pthread.h>
#include <stdatomic.h>
#include <stddef.h>
#include <stdint.h>

#include "ring_buffer.h"

/** @brief Найбільша довжина імені джерела разом із завершальним нулем. */
#define LOG_WRITER_SOURCE_SIZE 16

/** @brief Найбільша довжина одного рядка логу разом із завершальним нулем. */
#define LOG_WRITER_LINE_SIZE 64

/** @brief Підсумок роботи записувача. */
struct log_writer_stats {
	size_t written; /**< скільки рядків записано в файл */
	size_t failed;	/**< скільки чисел не вдалося записати (помилка запису) */
};

/** @brief Стан записувача. Поля змінюй лише через функції log_writer_*. */
struct log_writer {
	struct ring_buffer *source_buffer;
	char source[LOG_WRITER_SOURCE_SIZE];
	int fd;
	pthread_t thread;
	atomic_bool stop_requested;
	struct log_writer_stats stats;
};

/**
 * @brief Складає один рядок логу (разом із символом нового рядка) у масив out.
 *
 * Чиста функція без доступу до файлів і часу, тому її легко перевіряти тестом.
 *
 * @param out          куди писати
 * @param size         розмір масиву out у байтах
 * @param source       ім'я джерела: 1–15 символів a-z, 0-9, _ (інакше JSON довелося б екранувати)
 * @param timestamp_ms мітка часу в мілісекундах
 * @param value        значення відліку
 * @return довжина рядка без завершального нуля; -EINVAL, якщо out чи source NULL або ім'я
 *         джерела недопустиме; -ENOSPC, якщо рядок не влізає в size
 */
int log_writer_format_line(char *out, size_t size, const char *source, int64_t timestamp_ms,
			   int32_t value);

/**
 * @brief Відкриває лог-файл і запускає потік, що забирає числа з буфера й пише їх у файл.
 *
 * Файл створюється, якщо його нема, і дописується в кінець, якщо є.
 *
 * @param lw     записувач, який треба запустити
 * @param rb     буфер, з якого брати числа; має жити довше за записувач
 * @param source ім'я джерела для кожного рядка (див. log_writer_format_line)
 * @param path   шлях до лог-файлу
 * @return 0 при успіху; -EINVAL при NULL чи недопустимому імені; інакше мінус код помилки
 *         відкриття файлу або створення потоку
 */
int log_writer_start(struct log_writer *lw, struct ring_buffer *rb, const char *source,
		     const char *path);

/**
 * @brief Зупиняє записувач: дописує все, що ще лежить у буфері, закриває файл.
 *
 * Викликай ПІСЛЯ того, як виробники перестали класти числа в буфер: тоді жодне число
 * не загубиться. Після виклику lw більше не можна використовувати без нового start.
 *
 * @param lw    записувач, запущений через log_writer_start()
 * @param stats сюди пишеться підсумок (можна NULL, якщо підсумок не потрібен)
 * @return 0 при успіху; мінус код помилки закриття файлу чи -EINVAL, якщо lw дорівнює NULL
 */
int log_writer_stop(struct log_writer *lw, struct log_writer_stats *stats);

#endif /* LOG_WRITER_H */
