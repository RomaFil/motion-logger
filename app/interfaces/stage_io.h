/**
 * @file stage_io.h
 * @brief Інтерфейс між логікою «етап руху» (core/) і трьома світлодіодами (drivers/).
 *
 * Логіка нічого не знає про GPIO: їй потрібно лише показати, на якому етапі плата. Драйвер
 * gpiod_stage.c реалізує це для libgpiod, у тестах стоїть підробка. Правило залежностей те саме,
 * що й для sensor.h: core/ підключає цей файл, drivers/ теж, а з'єднує їх лише main.c.
 */
#ifndef STAGE_IO_H
#define STAGE_IO_H

/** @brief Етап руху: де плата відносно першого руху. Кожному відповідає свій світлодіод. */
enum stage {
	STAGE_BEFORE, /**< руху ще не було (світлодіод 1) */
	STAGE_MOVING, /**< плата рухається (світлодіод 2) */
	STAGE_AFTER,  /**< рух закінчився (світлодіод 3) */
};

/** @brief Три світлодіоди. Драйвер вбудовує цю структуру першим полем у свою. */
struct stage_io {
	/** Світить лише світлодіод етапу stage, решта вимкнені. @return 0 або мінус код помилки. */
	int (*show)(struct stage_io *self, enum stage stage);
	/** Вимикає світлодіоди й звільняє ресурси. Можна викликати лише один раз. */
	void (*close)(struct stage_io *self);
};

#endif /* STAGE_IO_H */
