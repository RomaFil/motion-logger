/**
 * @file motion_defaults.h
 * @brief Параметри виявлення руху за замовчуванням: єдине місце, де вони записані.
 *
 * Числа підібрано за справжнім записом 01.11.2026 (MPU6050 на платі Motion Logger, 60 с
 * спокою в руці й 60 с ходьби по квартирі, tests/data): у спокої середнє відхилення ≈ 0,010 g,
 * у ході ≈ 0,10 g, поріг стоїть між ними з запасом ≈ 2 рази від спокою. Це ОДИН запис однієї
 * людини в одному місці: у машині, на столі чи під час бігу значення можуть знадобитись
 * інші. Міняти їх тут: застосунок і інструмент analyze_recording (обидва беруть числа звідси)
 * одразу поводяться однаково.
 */
#ifndef MOTION_DEFAULTS_H
#define MOTION_DEFAULTS_H

/** @brief Скільки останніх відліків усереднює фільтр руху: 0,5 с при 100 відліках/с, цикл кроків.
 */
#define MOTION_DEFAULT_WINDOW 50

/**
 * @brief Поріг входу в рух: середнє відхилення довжини вектора від його повільного середнього, g.
 *
 * Вище за тряску плати в руці (до 0,028 g на записі 01.11.2026 о 22:47), щоб рука не запускала рух.
 */
#define MOTION_DEFAULT_THRESHOLD_G 0.03

/**
 * @brief Поріг виходу з руху, g: рух триває, поки середнє не впаде до цього значення.
 *
 * Нижчий за поріг входу (гістерезис): повільна ходьба просідає до 0,029 g (запис 01.11.2026) і
 * не повинна обриватись, а спокій з рукою не вище 0,017 g.
 */
#define MOTION_DEFAULT_RELEASE_G 0.015

/** @brief Скільки відповідей підряд підтверджують зміну стану (0,5 с при 100 відліках/с). */
#define MOTION_DEFAULT_CONFIRM 50

#endif /* MOTION_DEFAULTS_H */
