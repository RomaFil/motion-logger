/**
 * @file sample_reader.h
 * @brief Читає числа-відліки з файлового дескриптора й складає їх у кільцевий буфер.
 *
 * Читач не вміє нічого про датчики: для нього джерело це просто дескриптор, з якого
 * течуть числа int32_t по 4 байти (порядок байтів рідний для цього комп'ютера).
 * Сьогодні це канал (pipe) від програми-імітатора, пізніше сюди ж можна підключити
 * дескриптор справжнього драйвера. Бізнес-логіка від заліза відокремлена саме цим
 * інтерфейсом.
 *
 * Чекання зроблено через epoll: потік спить у ядрі, поки в дескрипторі нема даних,
 * і не крутить цикл "а чи є щось?". Тому процесор майже не завантажений.
 */
#ifndef SAMPLE_READER_H
#define SAMPLE_READER_H

#include <signal.h>
#include <stddef.h>

#include "ring_buffer.h"

/** @brief Підсумок роботи читача. */
struct sample_reader_stats {
	size_t received; /**< скільки чисел прочитано з джерела */
	size_t dropped;	 /**< скільки з них не влізло в повний буфер і втрачено */
};

/**
 * @brief Читає джерело, поки воно не закриється або не з'явиться прохання зупинитись.
 *
 * Функція блокує викликача. Число, яке не влізло в повний буфер, рахується в
 * stats->dropped і відкидається: читач не затримує джерело, а втрату видно в статистиці.
 *
 * @param source_fd дескриптор, який вміє epoll (канал, сокет, термінал; звичайний файл не вміє)
 * @param rb        буфер, ініціалізований через ring_buffer_init()
 * @param stop      прапорець зупинки: щойно стає ненульовим, функція повертається
 *                  (перевіряється принаймні раз на 100 мс)
 * @param stats     сюди пишеться підсумок; поля обнуляються на початку
 * @return 0, якщо джерело закрилось або була зупинка; -EINVAL, якщо будь-який покажчик
 *         NULL чи source_fd менший за нуль; інакше мінус код помилки системи
 */
int sample_reader_run(int source_fd, struct ring_buffer *rb, const volatile sig_atomic_t *stop,
		      struct sample_reader_stats *stats);

#endif /* SAMPLE_READER_H */
