/**
 * @file sensor.h
 * @brief Типи даних, спільні для ядра програми (core/) і джерел відліків.
 *
 * Ядро (буфер, фільтр, лог) нічого не знає про залізо. Воно оперує двома типами:
 *   - struct accel_sample: один відлік акселерометра (час і три осі в g);
 *   - struct sample: запис, що йде через кільцевий буфер від джерела до записувача логу.
 *
 * Правило залежностей: core/ підключає цей файл, а файли з drivers/ ніколи не підключає.
 */
#ifndef SENSOR_H
#define SENSOR_H

#include <stdint.h>

/** @brief Один відлік акселерометра. */
struct accel_sample {
	int64_t time_ms; /**< мілісекунди за годинником датчика (для запису з файлу: від його
			    початку) */
	double x_g;	 /**< прискорення по X, g */
	double y_g;	 /**< прискорення по Y, g */
	double z_g;	 /**< прискорення по Z, g */
};

/** @brief Звідки взято запис у буфері. */
enum sample_source {
	SAMPLE_SOURCE_SIM,   /**< імітатор sensor_sim: лише число-лічильник */
	SAMPLE_SOURCE_ACCEL, /**< акселерометр: три осі в g */
};

/**
 * @brief Запис, який іде через кільцевий буфер від джерела до записувача логу.
 *
 * Поле source каже, які з решти полів мають зміст: для SIM заповнено value, для ACCEL
 * заповнено x_g, y_g, z_g. Решта полів нулі. Мітка часу ставиться там, де відлік
 * з'явився (а не в момент запису в файл), тому затримка в буфері не псує час.
 */
struct sample {
	enum sample_source source;
	int64_t time_ms; /**< момент відліку, мілісекунди */
	int32_t value;	 /**< число імітатора (лише SAMPLE_SOURCE_SIM) */
	double x_g;	 /**< (лише SAMPLE_SOURCE_ACCEL) */
	double y_g;
	double z_g;
};

#endif /* SENSOR_H */
