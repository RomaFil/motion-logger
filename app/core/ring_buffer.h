/**
 * @file ring_buffer.h
 * @brief Потокобезпечний кільцевий буфер фіксованого розміру для записів struct sample.
 *
 * Кільцевий буфер це черга «першим прийшов, першим пішов» (FIFO) у масиві
 * фіксованого розміру. Коли індекс доходить до кінця масиву, він повертається на
 * початок, ніби масив скручений у кільце. Тому буферу не потрібна динамічна
 * пам'ять (malloc), і він працює за однаковий короткий час.
 *
 * Буфер НЕ перезаписує старі дані: якщо він повний, push повертає помилку.
 *
 * Потокобезпечність: усередині буфера є замок (mutex). Кожна публічна функція
 * бере замок на час своєї роботи, тому один потік може класти записи, а інший
 * одночасно їх забирати. Функції не блокуються в очікуванні даних чи місця:
 * вони одразу повертають -ENOSPC або -ENODATA, а що робити далі (почекати,
 * повторити), вирішує той, хто викликав.
 *
 * Пам'яттю під елементи володіє той, хто викликає: ring_buffer_init() лише
 * запам'ятовує вказівник на масив і не звільняє його. Після роботи викликай
 * ring_buffer_destroy(), щоб звільнити замок.
 */
#ifndef RING_BUFFER_H
#define RING_BUFFER_H

#include <pthread.h>
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#include "sensor.h"

/**
 * @brief Стан кільцевого буфера. Поля змінюй лише через функції ring_buffer_*.
 *
 * Ідея: head вказує, КУДИ писати наступний елемент, tail вказує, ЗВІДКИ читати
 * наступний. Лічильник count потрібен, щоб відрізнити порожній буфер від повного:
 * у обох випадках head == tail.
 */
struct ring_buffer {
	struct sample *items; /**< масив під елементи (належить викликачеві) */
	size_t capacity;      /**< скільки елементів вміщується в масив */
	size_t head;	      /**< індекс для наступного запису */
	size_t tail;	      /**< індекс для наступного читання */
	size_t count;	      /**< скільки елементів лежить у буфері зараз */
	pthread_mutex_t lock; /**< замок: захищає всі поля вище від одночасної зміни */
};

/**
 * @brief Готує буфер до роботи й створює його замок.
 *
 * @param rb       буфер, який треба ініціалізувати
 * @param storage  масив під елементи; має жити довше за буфер
 * @param capacity розмір масиву в елементах (не в байтах), більше нуля
 * @return 0 при успіху, -EINVAL, якщо rb чи storage рівні NULL або capacity дорівнює нулю,
 *         або мінус код помилки від створення замка
 */
int ring_buffer_init(struct ring_buffer *rb, struct sample *storage, size_t capacity);

/**
 * @brief Знищує замок буфера. Викликай, коли буфер більше не потрібен.
 *
 * Не можна викликати, поки інший потік ще користується буфером. Масив storage
 * функція не чіпає: ним володіє викликач. Якщо rb дорівнює NULL, нічого не робить.
 *
 * @param rb буфер, ініціалізований через ring_buffer_init()
 */
void ring_buffer_destroy(struct ring_buffer *rb);

/**
 * @brief Кладе один запис (копію) в кінець черги. Безпечно викликати з будь-якого потоку.
 *
 * @param rb    ініціалізований буфер
 * @param item  запис, який треба покласти
 * @return 0 при успіху, -ENOSPC, якщо буфер повний (нічого не змінюється),
 *         -EINVAL, якщо rb чи item дорівнюють NULL
 */
int ring_buffer_push(struct ring_buffer *rb, const struct sample *item);

/**
 * @brief Забирає найстаріший запис з початку черги. Безпечно викликати з будь-якого потоку.
 *
 * @param rb    ініціалізований буфер
 * @param item  куди записати забраний запис
 * @return 0 при успіху, -ENODATA, якщо буфер порожній (*item не змінюється),
 *         -EINVAL, якщо rb чи item дорівнюють NULL
 */
int ring_buffer_pop(struct ring_buffer *rb, struct sample *item);

/**
 * @brief Повертає, скільки записів зараз у буфері. Параметр rb не може бути NULL.
 *
 * Це знімок на мить виклику: поки ти читаєш відповідь, інший потік уже міг
 * покласти чи забрати запис. Параметр не const, бо функція бере замок.
 */
size_t ring_buffer_count(struct ring_buffer *rb);

/**
 * @brief Повертає true, якщо в буфері нічого немає (знімок на мить виклику).
 *        Параметр rb не може бути NULL.
 */
bool ring_buffer_is_empty(struct ring_buffer *rb);

/**
 * @brief Повертає true, якщо в буфері нема вільного місця (знімок на мить виклику).
 *        Параметр rb не може бути NULL.
 */
bool ring_buffer_is_full(struct ring_buffer *rb);

#endif /* RING_BUFFER_H */
