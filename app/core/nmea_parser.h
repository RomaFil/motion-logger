/**
 * @file nmea_parser.h
 * @brief Розбір полів рядків NMEA $..RMC і $..GGA у звичайну структуру.
 *
 * Що це за рядки:
 *   $GPRMC,123519,A,4807.038,N,01131.000,E,022.4,084.4,230394,003.1,W*6A
 *     (рекомендовані мінімальні дані: час, дійсність, позиція, швидкість, дата)
 *   $GPGGA,123519,4807.038,N,01131.000,E,1,08,0.9,545.4,M,46.9,M,,*47
 *     (фіксація: час, позиція, якість, кількість супутників, висота)
 *
 * Головна пастка: поки модуль не спіймав супутники, більшість полів ПОРОЖНІ
 * ($GPGGA,235947.00,,,,,0,00,99.99,,,,,,*6F). Порожнє поле не помилка, а нормальний
 * стан "даних ще нема". Тому кожне необов'язкове значення має пару has_*: перед
 * читанням значення дивись на прапорець. Інакше можна прийняти нуль широти за реальну
 * точку на екваторі.
 *
 * Координати в рядку записані як градуси-хвилини (ddmm.mmmm), а тут вони вже в
 * десяткових градусах: 48° 07,038' = 48 + 7,038/60 = 48,1173°. Південь і захід
 * мають знак мінус.
 */
#ifndef NMEA_PARSER_H
#define NMEA_PARSER_H

#include <stdbool.h>
#include <stdint.h>

/** @brief Розібрані дані одного рядка RMC або GGA. */
struct nmea_fix {
	bool has_time;		 /**< чи було в рядку поле часу */
	uint32_t seconds_of_day; /**< секунди від початку доби UTC (частки секунди відкинуто) */
	bool valid; /**< RMC: статус A; GGA: якість більше нуля. Інакше позиції вірити не можна */
	bool has_position;	  /**< чи були поля широти й довготи */
	double latitude_degrees;  /**< широта, десяткові градуси, південь мінусом */
	double longitude_degrees; /**< довгота, десяткові градуси, захід мінусом */
	bool has_speed;		  /**< лише RMC: чи було поле швидкості */
	double speed_knots;	  /**< швидкість у вузлах (1 вузол = 1,852 км/год) */
	bool has_satellites;	  /**< лише GGA: чи було поле кількості супутників */
	uint8_t satellites;	  /**< скільки супутників модуль використовує */
	bool has_date;		  /**< лише RMC: чи було поле дати ddmmyy */
	uint16_t year;		  /**< рік повністю: yy 80..99 дає 19yy, інакше 20yy */
	uint8_t month;		  /**< 1..12 */
	uint8_t day;		  /**< 1..31 */
};

/**
 * @brief Розбирає рядок RMC (GPRMC, GNRMC та інші), попередньо перевіривши контрольну суму.
 *
 * @param sentence рядок NMEA, завершений нулем
 * @param fix      сюди пишеться результат; при помилці лишається без змін
 * @return 0 при успіху; -EBADMSG, якщо сума не збіглась; -ENOMSG, якщо це рядок іншого
 *         типу; -EINVAL, якщо форма чи значення поля неправильні або NULL
 */
int nmea_parse_rmc(const char *sentence, struct nmea_fix *fix);

/**
 * @brief Розбирає рядок GGA (GPGGA, GNGGA та інші), попередньо перевіривши контрольну суму.
 *
 * Параметри й коди помилок ті самі, що в nmea_parse_rmc().
 */
int nmea_parse_gga(const char *sentence, struct nmea_fix *fix);

/**
 * @brief Час UTC рядка RMC у секундах Unix (від 1970-01-01 00:00:00 UTC).
 *
 * Потрібні і дата (has_date), і час (has_time): з GPS це єдине джерело справжнього часу на платі
 * без батарейки RTC.
 *
 * @return секунди Unix; -1, якщо fix NULL або дати чи часу в рядку не було
 */
int64_t nmea_utc_seconds(const struct nmea_fix *fix);

#endif /* NMEA_PARSER_H */
