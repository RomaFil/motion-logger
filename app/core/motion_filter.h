/**
 * @file motion_filter.h
 * @brief Фільтр руху: ковзне середнє відхилення прискорення від його повільного середнього і поріг.
 *
 * Акселерометр, що лежить нерухомо, не показує нуль: він відчуває силу тяжіння, тобто
 * вектор сталої довжини, спрямований вниз. Напрямок залежить від того, як лежить плата
 * (рівно, на боці, під кутом), а довжина вектора не змінюється. Під час руху плату
 * трясе, і довжина вектора коливається навколо цього значення.
 *
 * Номінально довжина дорівнює 1 g, але справжній датчик помиляється на кілька відсотків:
 * на записі 01.11.2026 нерухомий MPU6050 показував 0,942 g. Якщо мірити відхилення від
 * ідеальної 1 g, спокій виглядає як постійний "рух" (0,058 g при порозі 0,05).
 * Тому фільтр порівнює довжину вектора не з 1 g, а з ЇЇ ВЛАСНИМ повільним середнім
 * (експоненційне середнє за MOTION_FILTER_BASELINE_SAMPLES відліків):
 *   відхилення = | sqrt(x² + y² + z²) − середнє |
 * Таке число не залежить ні від нахилу плати, ні від похибки масштабу датчика. Далі воно
 * усереднюється за останніми window_size відліками (ковзне середнє: нове число витісняє
 * найстаріше), що згладжує поодинокі викиди шуму. Рух є, якщо це середнє СТРОГО БІЛЬШЕ за
 * поріг. Стале прискорення без змін (наприклад, довгий рівномірний розгін) рухом не
 * вважається: фільтр бачить лише коливання.
 *
 * Поки не набрано повне вікно відліків, фільтр каже "руху нема": одного першого
 * відліку замало, щоб щось стверджувати. Перший відлік задає середнє, тому на старті
 * відхилення нуль.
 *
 * Фільтр НЕ потокобезпечний: його має викликати один потік. Одиниця виміру всюди g
 * (не м/с²): перерахунок із "сирих" одиниць датчика робить драйвер.
 */
#ifndef MOTION_FILTER_H
#define MOTION_FILTER_H

#include <stdbool.h>
#include <stddef.h>

/** @brief Найбільший дозволений розмір вікна. Масив у структурі має саме такий розмір. */
#define MOTION_FILTER_MAX_WINDOW 64

/**
 * @brief Скільки відліків згладжує середнє довжини вектора: 300 відліків це 3 с при 100 Гц.
 *
 * Менше значення швидше пристосовується до зміни температури чи нахилу, але під час
 * довгої ходьби "розчиняє" коливання у своєму середньому. Значення підібрано за записом
 * 01.11.2026 (результат майже не залежав від 100..1000).
 */
#define MOTION_FILTER_BASELINE_SAMPLES 300

/** @brief Стан фільтра. Поля змінюй лише через функції motion_filter_*. */
struct motion_filter {
	double deviations[MOTION_FILTER_MAX_WINDOW]; /**< останні відхилення, g (кільце) */
	size_t window_size;			     /**< скільки відліків усереднюємо */
	size_t next;				     /**< куди писати наступне відхилення */
	size_t count;	     /**< скільки відхилень вже набрано (до window_size) */
	double threshold_g;  /**< поріг руху, g */
	double baseline_g;   /**< повільне середнє довжини вектора, g */
	bool baseline_ready; /**< чи вже є перший відлік, що задав середнє */
};

/**
 * @brief Готує фільтр: порожнє вікно, заданий розмір і поріг.
 *
 * @param filter      фільтр, який треба ініціалізувати
 * @param window_size скільки відліків усереднювати: 1..MOTION_FILTER_MAX_WINDOW
 * @param threshold_g поріг у g: нуль або більше (число, не NaN)
 * @return 0 при успіху; -EINVAL, якщо filter дорівнює NULL, window_size поза межами
 *         або threshold_g від'ємний чи не число
 */
int motion_filter_init(struct motion_filter *filter, size_t window_size, double threshold_g);

/**
 * @brief Додає відлік прискорення (три осі, в g) і витісняє найстаріший, якщо вікно повне.
 *
 * @param filter фільтр, ініціалізований через motion_filter_init()
 * @param x      прискорення по осі X, g
 * @param y      прискорення по осі Y, g
 * @param z      прискорення по осі Z, g
 * @return 0 при успіху; -EINVAL, якщо filter NULL або будь-яка вісь не є скінченним
 *         числом (NaN чи нескінченність); у такому разі стан фільтра не змінюється
 */
int motion_filter_add_sample(struct motion_filter *filter, double x, double y, double z);

/**
 * @brief Повертає середнє відхилення за поточне вікно, в g.
 *
 * Корисне для підбору порога: запиши це число для "стою" і для "іду" й постав поріг
 * між ними. Поки вікно не повне, усереднюється те, що набрано; порожнє вікно дає 0.
 *
 * @param filter фільтр
 * @return середнє відхилення, g
 */
double motion_filter_get_average(const struct motion_filter *filter);

/**
 * @brief Каже, чи є рух: вікно повне і середнє відхилення строго більше за поріг.
 *
 * @param filter фільтр
 * @return true, якщо рух виявлено
 */
bool motion_filter_is_moving(const struct motion_filter *filter);

#endif /* MOTION_FILTER_H */
