/**
 * @file button_filter.h
 * @brief Натискання кнопки як перехід «відпущено → натиснуто». Чиста логіка без заліза й часу.
 *
 * Драйвер після кожної події на лінії кнопки чекає, поки контакт заспокоїться, зчитує справжній
 * рівень лінії й передає сюди, чи вона зараз «натиснута». Натисканням вважається лише перехід із
 * «відпущено» в «натиснуто». Поки кнопку тримають, а також поки контакт дрижить після відпускання й
 * у підсумку лишається відпущеним, нових натискань нема.
 *
 * Без цього короткий імпульс дрижання при відпусканні, що трапився пізніше за вікно
 * RECORDING_UI_DEBOUNCE_MS, сприймався як нове натискання й знімав паузу одразу після відпускання
 * кнопки (05.11.2026, виявлено на платі).
 */
#ifndef BUTTON_FILTER_H
#define BUTTON_FILTER_H

#include <stdbool.h>

/** @brief Стан фільтра. Поля змінюй лише через функції button_filter_*. */
struct button_filter {
	bool down; /**< чи вважається кнопка зараз натиснутою */
};

/** @brief Початковий стан: кнопку відпущено. */
void button_filter_init(struct button_filter *filter);

/**
 * @brief Додає зчитаний рівень кнопки.
 * @param active true, якщо лінія зараз у стані «натиснуто»
 * @return true лише при переході «відпущено → натиснуто»
 */
bool button_filter_update(struct button_filter *filter, bool active);

#endif /* BUTTON_FILTER_H */
