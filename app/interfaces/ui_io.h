/**
 * @file ui_io.h
 * @brief Інтерфейс між логікою «кнопка й світлодіод» (core/) і залізом (drivers/).
 *
 * Логіка нічого не знає про GPIO: їй потрібні лише дві речі, дочекатись натискання кнопки і
 * показати колір. Драйвер gpiod_ui.c реалізує це для libgpiod, у тестах стоїть підробка.
 * Правило залежностей те саме, що й для sensor.h: core/ підключає цей файл, drivers/ теж, а
 * з'єднує їх лише main.c.
 */
#ifndef UI_IO_H
#define UI_IO_H

/** @brief Колір світлодіода: стан запису. */
enum ui_color {
	UI_COLOR_BLUE,	/**< запис на паузі */
	UI_COLOR_GREEN, /**< записуємо, плата стоїть */
	UI_COLOR_RED,	/**< записуємо, плата рухається */
};

/** @brief Кнопка і світлодіод. Драйвер вбудовує цю структуру першим полем у свою. */
struct ui_io {
	/**
	 * Чекає натискання кнопки не довше timeout_ms мілісекунд.
	 * @return 1, якщо кнопку натиснули; 0, якщо час вийшов або чекання перервав сигнал;
	 *         мінус код помилки
	 */
	int (*wait_press)(struct ui_io *self, int timeout_ms);
	/** Показує колір. @return 0 або мінус код помилки. */
	int (*set_color)(struct ui_io *self, enum ui_color color);
	/** Вимикає світлодіод і звільняє ресурси. Можна викликати лише один раз. */
	void (*close)(struct ui_io *self);
};

#endif /* UI_IO_H */
