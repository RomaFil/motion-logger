/**
 * @file ui_io.h
 * @brief Інтерфейс між логікою «кнопка й світлодіоди» (core/) і залізом (drivers/).
 *
 * Логіка нічого не знає про GPIO: їй потрібні лише дві речі, дочекатись натискання кнопки і
 * показати, що відбувається. Драйвер gpiod_ui.c реалізує це для libgpiod, у тестах стоїть
 * підробка. Правило залежностей те саме, що й для sensor.h: core/ підключає цей файл, drivers/
 * теж, а з'єднує їх лише main.c.
 */
#ifndef UI_IO_H
#define UI_IO_H

/**
 * @brief Що показують три світлодіоди. Етапам руху відповідають світлодіоди 1, 2 і 3 (зліва
 *        направо на платі), паузі всі три разом.
 */
enum ui_view {
	UI_VIEW_BEFORE, /**< запис іде, руху ще не було (світлодіод 1) */
	UI_VIEW_MOVING, /**< запис іде, плата рухається (світлодіод 2) */
	UI_VIEW_AFTER,	/**< запис іде, рух закінчився (світлодіод 3) */
	UI_VIEW_PAUSED, /**< запис на паузі (світяться всі три) */
};

/** @brief Кнопка і світлодіоди. Драйвер вбудовує цю структуру першим полем у свою. */
struct ui_io {
	/**
	 * Чекає натискання кнопки не довше timeout_ms мілісекунд. Без кнопки просто чекає час.
	 * @return 1, якщо кнопку натиснули; 0, якщо час вийшов або чекання перервав сигнал;
	 *         мінус код помилки
	 */
	int (*wait_press)(struct ui_io *self, int timeout_ms);
	/** Показує стан view. @return 0 або мінус код помилки. */
	int (*show)(struct ui_io *self, enum ui_view view);
	/** Вимикає світлодіоди й звільняє ресурси. Можна викликати лише один раз. */
	void (*close)(struct ui_io *self);
};

#endif /* UI_IO_H */
