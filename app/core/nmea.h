/**
 * @file nmea.h
 * @brief Перевірка рядків протоколу NMEA 0183, які надсилає GPS-модуль (NEO-6M).
 *
 * Рядок NMEA виглядає так:
 *   $GPGLL,4916.45,N,12311.12,W,225444,A,*1D\r\n
 * Це символ '$', тіло (поля через коми), символ '*', контрольна сума з двох
 * шістнадцяткових цифр і кінець рядка. Контрольна сума це "виключне АБО" (XOR) усіх
 * символів тіла, тобто всього, що стоїть між '$' і '*'. Якщо під час передачі по дроту
 * хоч один символ спотворився, сума майже напевно не збіжиться, і рядок треба відкинути.
 *
 * Модуль нічого не читає з портів і не розбирає поля: лише відповідає на питання
 * "рядок цілий чи пошкоджений". Розбір полів буде в наступних кроках.
 */
#ifndef NMEA_H
#define NMEA_H

#include <stddef.h>
#include <stdint.h>

/** @brief Найбільша довжина рядка NMEA за стандартом: 82 символи, разом з '$' і \r\n. */
#define NMEA_MAX_SENTENCE_LENGTH 82

/**
 * @brief Рахує контрольну суму NMEA: XOR усіх байтів тіла.
 *
 * @param payload тіло рядка (те, що між '$' і '*', без самих цих символів)
 * @param length  скільки байтів брати
 * @return контрольна сума; для порожнього тіла це 0
 */
uint8_t nmea_compute_checksum(const char *payload, size_t length);

/**
 * @brief Перевіряє, що рядок NMEA має правильну форму і збіжну контрольну суму.
 *
 * Дозволено лише один із кінців рядка: нічого, "\n" або "\r\n". Цифри суми можуть бути
 * великими чи малими літерами. Рядок має бути завершений нулем і не довшим за
 * NMEA_MAX_SENTENCE_LENGTH.
 *
 * @param sentence рядок, що починається з '$'
 * @return 0, якщо рядок цілий; -EINVAL, якщо він має неправильну форму (нема '$' чи '*',
 *         сума не з двох шістнадцяткових цифр, зайві символи після суми, надто довгий,
 *         sentence дорівнює NULL); -EBADMSG, якщо форма правильна, але сума не збігається
 */
int nmea_verify_checksum(const char *sentence);

#endif /* NMEA_H */
