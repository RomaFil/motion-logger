/**
 * @file accel_csv.h
 * @brief Розбір рядка запису акселерометра у форматі CSV: t_ms,x_g,y_g,z_g.
 *
 * Приклад рядка:  20460,0.1772,-0.0922,0.7738
 * Перший стовпець це мілісекунди від початку запису (ціле, не менше нуля), решта три
 * це прискорення по осях X, Y, Z в g (десяткові числа, можуть бути від'ємні).
 *
 * Порожні рядки й рядки, що починаються з '#', це коментарі: розбір повідомляє, що
 * даних у них нема, і викликач їх пропускає.
 *
 * Формат спільний для синтетичних тестових даних і для справжнього запису з плати, тож
 * заміна файлу не потребує змін у коді.
 */
#ifndef ACCEL_CSV_H
#define ACCEL_CSV_H

#include <stdint.h>

/** @brief Один відлік акселерометра. */
struct accel_sample {
	int64_t time_ms; /**< мілісекунди від початку запису */
	double x_g;	 /**< прискорення по X, g */
	double y_g;	 /**< прискорення по Y, g */
	double z_g;	 /**< прискорення по Z, g */
};

/** @brief Найбільша довжина рядка CSV разом з кінцем рядка і завершальним нулем. */
#define ACCEL_CSV_MAX_LINE 128

/**
 * @brief Розбирає один рядок CSV.
 *
 * @param line   рядок, завершений нулем; кінець рядка "\n" чи "\r\n" допустимий
 * @param sample сюди пишеться результат; при помилці лишається без змін
 * @return 0, якщо в рядку був відлік; -ENODATA, якщо це порожній рядок чи коментар
 *         (пропусти його); -EINVAL, якщо рядок неправильний (не чотири поля, не число,
 *         від'ємний час, надто довгий) чи будь-який покажчик NULL
 */
int accel_csv_parse_line(const char *line, struct accel_sample *sample);

#endif /* ACCEL_CSV_H */
