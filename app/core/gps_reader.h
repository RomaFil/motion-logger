/**
 * @file gps_reader.h
 * @brief Читає рядки NMEA з файлового дескриптора, розбирає їх і кладе в кільцевий буфер.
 *
 * Читач нічого не знає про залізо: джерело це дескриптор, з якого течуть байти (послідовний порт
 * GPS, канал у тестах). Як і sample_reader, чекає через epoll: потік спить у ядрі, поки нема даних.
 *
 * Що робить з рядками:
 *   - збирає байти в рядки по символу '\n' (символ '\r' перед ним відкидається), рядок довший за
 *     GPS_READER_LINE_MAX вважається зіпсованим і викидається цілком;
 *   - перевіряє контрольну суму й розбирає $..RMC та $..GGA через nmea_parser;
 *   - на КОЖЕН дійсний рядок RMC кладе один запис SAMPLE_SOURCE_GPS (раз на секунду для модуля
 * NEO-6M), з позицією й швидкістю, якщо статус A, і кількістю супутників з останнього GGA (або -1,
 * якщо GGA ще не було);
 *   - всі інші типи рядків (GSV, TXT, GSA тощо) мовчки пропускає.
 *
 * Дійсність позиції береться з RMC, а не з GGA: поки модуль не спіймав супутників, запис усе одно
 * з'являється, але з gps_fix = false і без координат. Це важливо: нульову широту не можна
 * сприймати як точку на екваторі.
 */
#ifndef GPS_READER_H
#define GPS_READER_H

#include <signal.h>
#include <stddef.h>

#include "ring_buffer.h"

/** @brief Найбільша довжина рядка NMEA разом із кінцем рядка (стандарт обмежує 82 символами). */
#define GPS_READER_LINE_MAX 128

/** @brief Підсумок роботи читача. */
struct gps_reader_stats {
	size_t lines;	     /**< скільки рядків прийнято (з правильним і зіпсованим вмістом) */
	size_t samples;	     /**< скільки записів GPS покладено в буфер (рядків RMC) */
	size_t dropped;	     /**< скільки з них не влізло в повний буфер */
	size_t bad_checksum; /**< скільки рядків з неправильною контрольною сумою */
	size_t malformed;    /**< скільки рядків неправильної форми чи задовгих */
};

/**
 * @brief Читає джерело, поки воно не закриється або не з'явиться прохання зупинитись.
 *
 * Функція блокує викликача. Запис, що не влізає в повний буфер, рахується в stats->dropped.
 *
 * @param source_fd дескриптор, який вміє epoll (послідовний порт, канал)
 * @param rb        буфер, ініціалізований через ring_buffer_init()
 * @param stop      прапорець зупинки (перевіряється принаймні раз на 100 мс)
 * @param stats     сюди пишеться підсумок; поля обнуляються на початку
 * @return 0, якщо джерело закрилось або була зупинка; -EINVAL, якщо будь-який покажчик NULL чи
 *         source_fd менший за нуль; інакше мінус код помилки системи
 */
int gps_reader_run(int source_fd, struct ring_buffer *rb, const volatile sig_atomic_t *stop,
		   struct gps_reader_stats *stats);

#endif /* GPS_READER_H */
